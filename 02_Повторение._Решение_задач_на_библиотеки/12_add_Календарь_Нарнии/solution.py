"""
Задача: Календарь Нарнии
Категория: Дополнительные задачи
Ограничение времени: 1 секунда
Ограничение памяти: 64 Мб

Условие:
В Нарнии свой календарь. В нем, как и у нас, 365 дней, но неделя состоит из 8 дней:  
`Понд, Вторнд, Тринд, Четв, Пятн, Шестн, Седьмидень, Восьмидень`.

В месяце всегда ровно 5 недель (40 дней), поэтому в году 9 месяцев и 5 дополнительных праздничных дней, которые не входят ни в один месяц.

Названия месяцев:

1. Лев
2. Колдунья
3. Фавн
4. Бобр
5. Кентавр
6. Орланд
7. Древо
8. Фонарь
9. Дуб

Праздничные дни Великого Льва (следуют после 9-го месяца):

* День Творения
* День Пробуждения
* День Даров
* День Пророчества
* День Возвращения

Первый день года (`1 Лев`) — это `Понд`.

Напишите программу, которая:

1. Сначала принимает дату в нашем мире, которая соответствует первому дню года в Нарнии (например, 25.12.2024).
2. Затем принимает дату в Нарнии в формате: сначала число, потом месяц (например, `3 Лев` или `День Творения` для праздничного дня).
3. Программа должна определить, какой это день недели:

* в Нарнии (название из 8-дневной недели или номер праздничного дня);
* в нашем мире (Понедельник, Вторник, ...).

Программа выводит две строки:

* день недели в Нарнии (или число — номер праздничного дня);
* день недели и дата в нашем мире через запятую и пробел.

В решении используйте модуль `datetime`.

Пример:
--- Пример 1 ---
Ввод:
25.12.2024
3 Лев
Вывод:
Тринд
Пятница, 27.12.2024

"""

from datetime import datetime, timedelta

w = ['Понд', 'Вторнд', 'Тринд', 'Четв', 'Пятн', 'Шестн', 'Седьмидень', 'Восьмидень']
m = ['Лев', 'Колдунья', 'Фавн', 'Бобр', 'Кентавр', 'Орланд', 'Древо', 'Фонарь', 'Дуб']
h = ['День Творения', 'День Пробуждения', 'День Даров', 'День Пророчества', 'День Возвращения']
r = ['Понедельник', 'Вторник', 'Среда', 'Четверг', 'Пятница', 'Суббота', 'Воскресенье']


def main():
    a = datetime.strptime(input().strip(), '%d.%m.%Y')
    s = input().strip()
    if s in h:
        n = 360 + h.index(s)
        print(h.index(s) + 1)
    else:
        d, mn = s.split()
        n = m.index(mn) * 40 + int(d) - 1
        print(w[n % 8])
    b = a + timedelta(days=n)
    print(f'{r[b.weekday()]}, {b.strftime("%d.%m.%Y")}')


if __name__ == "__main__":
    main()
